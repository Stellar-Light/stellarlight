/**
 * The verified Stellar RWA registry — every real-world-asset token rwa.xyz
 * lists on Stellar (97 tokens, 52 issuers on 2026-09-04), each re-verified
 * on-chain before it went in here — PLUS, since 2026-09-09 (sls-083), every
 * other asset a TRACKED issuer's own stellar.toml declares under a tracked
 * issuer account (six rows), so an issuer this registry covers is covered
 * completely: a consumer reading Etherfuse's five products had no way to know
 * the toml declared nine. `rwaxyzListed` says which rule admitted a row;
 * rwa.xyz figures are null on issuer-declared rows (not provided — never
 * zero). RWA_ISSUER_COVERAGE below records what each tracked issuer's toml
 * declared on the day it was reconciled; the unit test holds the registry to
 * it, and scripts/data/reconcile-rwa-issuers.ts re-reads the tomls live.
 *
 * Why it exists: a project row being "Live" says nothing about whether a
 * PRODUCT is issued on Stellar today (sls-023). DTCC was Live while its
 * Stellar connection is planned for H1 2027; WisdomTree's row could not tell
 * you it has 18 live funds. These rows carry the product-level facts a
 * project row cannot — and they feed `products` on the project row.
 *
 * How a row earned its place (verificationLevel), strongest first:
 *   toml-bidirectional   the ISSUER's own stellar.toml names this (code,
 *                        issuer) AND the issuer account's home_domain points
 *                        back. A squatter controls its own home_domain; it
 *                        cannot edit Franklin Templeton's toml.
 *   entity-toml          the entity's toml names the issuer, but the issuer's
 *                        home_domain points at the minting tool (lobstr.co).
 *   contract-metadata    a Soroban token: name/symbol/decimals read from the
 *                        contract itself via RPC, and total_supply where the
 *                        contract exposes it (null otherwise: LIQVID×2, TPT30), listed by
 *                        rwa.xyz under this issuer. Horizon's /assets never
 *                        sees these — Spiko, the #1 RWA issuer on Stellar,
 *                        is invisible to it.
 *   on-chain-home-domain the asset is issued and the issuer's home_domain is
 *                        the entity's, but its toml omits this one asset.
 *   on-chain-only        issued on mainnet; the toml was a could-not-check
 *                        (403/308/DNS) or the issuer has no home_domain.
 *
 * Verified from the entity OUTWARD, never from the asset code inward: BENJI
 * has 22 issuers on mainnet and five embed "franklintempleton" in a scam
 * subdomain. Only the registrable domain matters.
 *
 * state: live (minted, at least two holders — someone other than the issuer
 * holds it) | issued-single-holder (minted, exactly one holder: the issuer or
 * its custodian; a real security, no secondary activity — 35 rows on
 * 2026-09-04, mostly tokenized Brazilian credit and real-estate tranches) |
 * deployed-no-supply (a Soroban contract that exists with zero supply and
 * zero events, or a classic asset the issuer declares that has trustlines but
 * nothing minted — CETESZ, FOCGX) | not-found (a listing that no longer
 * resolves). Only live and issued-single-holder are minted on mainnet and may
 * lend deployment evidence; only live is served as a live product.
 *
 * productKind follows rwa.xyz's asset class on listed rows; on issuer-declared
 * rows (no rwa.xyz class to follow) it follows the toml's own
 * anchor_asset_type — fiat → stablecoin, anything else → rwa-asset.
 *
 * pairedWith: six real-estate tranches were deployed TWICE — same wasm, same
 * deployer, minutes apart, identical supply, one holder each — and rwa.xyz
 * lists both. Neither can be shown canonical from chain data, so both rows
 * stay, linked, and a project receives ONE product per pair.
 * rwaxyz* fields are rwa.xyz's own figures, kept so a $500M row with one
 * holder and eight events can be read for what it is: value is not activity.
 *
 * CURATED, not discovered: absence here means untracked, never "not on
 * Stellar". Add a row only after the same verification.
 *
 * projectSlug joins were checked by DESCRIPTION, not name — three directory
 * slugs are namesakes, not the issuer: `janus` is a Hamburg freight-payments
 * platform (not Janus Henderson / Anemoy), `mesh` is a crypto-payments
 * network (not Mesh Trade, the mZAR issuer), `forge` is a node-deployment SDK
 * (not Societe Generale-FORGE, the EURCV issuer). Those rows carry null on
 * purpose; re-joining them attributes a fund to a stranger.
 *
 * controls (classic assets only): the issuer's on-chain flags, read from
 * Horizon — the whitelisting and clawback controls GT-18 asked for, as
 * facts rather than prose. authRequired = holders must be approved by the
 * issuer (a whitelist); authRevocable = the issuer can freeze a holder;
 * clawbackEnabled = the issuer can pull tokens back; authImmutable = the
 * issuer has given those powers up for good. null on Soroban tokens: their
 * controls live in contract logic and are not uniformly readable.
 */

/**
 * The four enums below are the ONE value set for each dimension. The route's
 * validator, the OpenAPI request/response enums and the tests all import them;
 * sls-082 found the state enum hand-copied into the spec twice and both copies
 * missing issued-single-holder while the handler accepted it.
 */
export const RWA_VERIFICATION_LEVELS = [
	"toml-bidirectional",
	"entity-toml",
	"contract-metadata",
	"on-chain-home-domain",
	"on-chain-only",
] as const;
export type RwaVerificationLevel = (typeof RWA_VERIFICATION_LEVELS)[number];

export const RWA_STATES = [
	"live",
	"issued-single-holder",
	"deployed-no-supply",
	"not-found",
] as const;
export type RwaState = (typeof RWA_STATES)[number];

export const RWA_KINDS = ["classic", "soroban"] as const;
export type RwaKind = (typeof RWA_KINDS)[number];

export const RWA_PRODUCT_KINDS = ["rwa-asset", "stablecoin"] as const;
export type RwaProductKind = (typeof RWA_PRODUCT_KINDS)[number];

export interface RwaAsset {
	/** `CODE-GISSUER` for a classic asset, the `C…` id for a Soroban token. */
	id: string;
	kind: RwaKind;
	name: string;
	symbol: string;
	issuerEntity: string | null;
	/** Directory project this joins onto (feeds its `products`); null = the issuer has no project row. */
	projectSlug: string | null;
	code: string | null;
	issuer: string | null;
	contract: string | null;
	productKind: RwaProductKind;
	assetClass: string | null;
	network: "mainnet";
	state: RwaState;
	/** Contract creation date (Soroban) — null for classic assets, where Horizon does not date issuance. */
	launchedAt: string | null;
	verifiedAt: string;
	evidenceUrl: string;
	verificationLevel: RwaVerificationLevel;
	basisNote: string | null;
	decimals: number | null;
	/** Read from the contract's total_supply() (Soroban); null where the contract has no such function. */
	totalSupply: number | null;
	horizonNote: string | null;
	/** The issuer toml's own `status` for this asset (SEP-1: live | private | test …) on the rows whose toml block was read; null = not read, never "live". `private` = the issuer says it is a restricted offering (SBRL: KYC-gated, not publicly tradable) and the product record says so. */
	tomlStatus: string | null;
	/** true = rwa.xyz lists this token on Stellar (the original inclusion rule); false = admitted because a tracked issuer's own toml declares it. */
	rwaxyzListed: boolean;
	/** rwa.xyz's own figures; null when rwa.xyz does not list the row (see rwaxyzListed) — not provided, never zero. */
	rwaxyzValueUsd: number | null;
	rwaxyzHolders: number | null;
	/** The sibling contract when the same tranche was deployed twice (see header); null otherwise. */
	pairedWith: string | null;
	/** Issuer flags from Horizon (classic only); null on Soroban tokens. */
	controls: {
		authRequired: boolean;
		authRevocable: boolean;
		authImmutable: boolean;
		clawbackEnabled: boolean;
	} | null;
	controlsBasis: "horizon-issuer-flags" | null;
}

