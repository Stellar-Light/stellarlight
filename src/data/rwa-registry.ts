/**
 * The verified Stellar RWA registry — every real-world-asset token rwa.xyz
 * lists on Stellar (97 tokens, 52 issuers on 2026-09-04), each re-verified
 * on-chain before it went in here.
 *
 * Why it exists: a project row being "Live" says nothing about whether a
 * PRODUCT is issued on Stellar today (sls-023). DTCC was Live while its
 * Stellar connection is planned for H1 2027; WisdomTree's row could not tell
 * you it has 18 live funds. These rows carry the product-level facts a
 * project row cannot — and they feed `products` on the project row.
 *
 * How a row earned its place (verificationLevel), strongest first:
 *   toml-bidirectional   the ISSUER's own stellar.toml names this (code,
 *                        issuer) AND the issuer account's home_domain points
 *                        back. A squatter controls its own home_domain; it
 *                        cannot edit Franklin Templeton's toml.
 *   entity-toml          the entity's toml names the issuer, but the issuer's
 *                        home_domain points at the minting tool (lobstr.co).
 *   contract-metadata    a Soroban token: name/symbol/decimals/total_supply
 *                        read from the contract itself via RPC, listed by
 *                        rwa.xyz under this issuer. Horizon's /assets never
 *                        sees these — Spiko, the #1 RWA issuer on Stellar,
 *                        is invisible to it.
 *   on-chain-home-domain the asset is issued and the issuer's home_domain is
 *                        the entity's, but its toml omits this one asset.
 *   on-chain-only        issued on mainnet; the toml was a could-not-check
 *                        (403/308/DNS) or the issuer has no home_domain.
 *
 * Verified from the entity OUTWARD, never from the asset code inward: BENJI
 * has 22 issuers on mainnet and five embed "franklintempleton" in a scam
 * subdomain. Only the registrable domain matters.
 *
 * state: live | deployed-no-supply (contract exists, zero supply and zero
 * events — deployed, never used; NOT served as a live product) | not-found.
 * rwaxyz* fields are rwa.xyz's own figures, kept so a $500M row with one
 * holder and eight events can be read for what it is: value is not activity.
 *
 * CURATED, not discovered: absence here means untracked, never "not on
 * Stellar". Add a row only after the same verification.
 *
 * projectSlug joins were checked by DESCRIPTION, not name — three directory
 * slugs are namesakes, not the issuer: `janus` is a Hamburg freight-payments
 * platform (not Janus Henderson / Anemoy), `mesh` is a crypto-payments
 * network (not Mesh Trade, the mZAR issuer), `forge` is a node-deployment SDK
 * (not Societe Generale-FORGE, the EURCV issuer). Those rows carry null on
 * purpose; re-joining them attributes a fund to a stranger.
 */

export type RwaVerificationLevel =
	| "toml-bidirectional"
	| "entity-toml"
	| "contract-metadata"
	| "on-chain-home-domain"
	| "on-chain-only";

export type RwaState = "live" | "deployed-no-supply" | "not-found";

export interface RwaAsset {
	/** `CODE-GISSUER` for a classic asset, the `C…` id for a Soroban token. */
	id: string;
	kind: "classic" | "soroban";
	name: string;
	symbol: string;
	issuerEntity: string | null;
	/** Directory project this joins onto (feeds its `products`); null = the issuer has no project row. */
	projectSlug: string | null;
	code: string | null;
	issuer: string | null;
	contract: string | null;
	productKind: "rwa-asset" | "stablecoin";
	assetClass: string | null;
	network: "mainnet";
	state: RwaState;
	/** Contract creation date (Soroban) — null for classic assets, where Horizon does not date issuance. */
	launchedAt: string | null;
	verifiedAt: string;
	evidenceUrl: string;
	verificationLevel: RwaVerificationLevel;
	basisNote: string | null;
	decimals: number | null;
	/** Read from the contract's total_supply() (Soroban); null where the contract has no such function. */
	totalSupply: number | null;
	horizonNote: string | null;
	rwaxyzValueUsd: number | null;
	rwaxyzHolders: number | null;
}

